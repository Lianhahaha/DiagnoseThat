"""Generates the Midnight app icon set: lime tile with the dark Pulse mark.

Matches the icon rail tile in the app (PulseTokens.accent / onAccent) and the
installer images. Writes, under apps/pulse_app/:
  assets/branding/app_icon.svg            vector source (empty state, docs)
  assets/branding/app_icon[_N].png        16-512 px rasters (tray, README, MSIX)
  assets/branding/taskbar_icon.png        256 px
  assets/branding/mark.png                128 px lime mark on transparent
  assets/branding/app_icon.ico            multi-size icon (tray)
  windows/runner/resources/app_icon.ico   Pulse.exe / taskbar icon

Small sizes (<= 32 px) use a larger, thicker mark so it stays legible.

Usage:  python tools/branding/make_app_icons.py
Requires Pillow.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "apps" / "pulse_app"
BRANDING = APP / "assets" / "branding"
RUNNER_ICO = APP / "windows" / "runner" / "resources" / "app_icon.ico"

LIME = "#C8F04A"
INK = "#08080A"

# Geometry in a 32-unit box (mark.svg uses the same peak).
VIEW = 32
TILE_RADIUS = 7
MARK_PEAK = [(4, 23), (10, 23), (14.5, 7), (19, 23), (28, 23)]
MARK_DOT = (14.5, 7)
MARK_DOT_RADIUS = 2.25

# Mark scale inside the tile and stroke width (mark units), per size class.
REGULAR = {"scale": 0.62, "stroke": 2.9}
SMALL = {"scale": 0.76, "stroke": 3.2}
SMALL_MAX_PX = 32

PNG_SIZES = (16, 24, 32, 48, 64, 128, 256, 512)
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)
SUPERSAMPLE = 8


def _hex(color):
    color = color.lstrip("#")
    return tuple(int(color[i : i + 2], 16) for i in (0, 2, 4))


def _mark_transform(style):
    offset = VIEW * (1 - style["scale"]) / 2
    return offset, style["scale"]


def render(px):
    """Rasterizes the icon at px x px with supersampling."""
    style = SMALL if px <= SMALL_MAX_PX else REGULAR
    big = px * SUPERSAMPLE
    unit = big / VIEW
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    draw.rounded_rectangle((0, 0, big - 1, big - 1), radius=TILE_RADIUS * unit, fill=_hex(LIME))

    offset, scale = _mark_transform(style)
    to_px = lambda x, y: ((offset + x * scale) * unit, (offset + y * scale) * unit)
    points = [to_px(x, y) for x, y in MARK_PEAK]
    width = style["stroke"] * scale * unit
    draw.line(points, fill=_hex(INK), width=round(width), joint="curve")
    for x, y in (points[0], points[-1]):
        draw.ellipse((x - width / 2, y - width / 2, x + width / 2, y + width / 2), fill=_hex(INK))
    cx, cy = to_px(*MARK_DOT)
    r = MARK_DOT_RADIUS * scale * unit
    draw.ellipse((cx - r, cy - r, cx + r, cy + r), fill=_hex(INK))
    return img.resize((px, px), Image.LANCZOS)


def render_mark(px):
    """Lime mark alone on transparent (mark.png)."""
    big = px * SUPERSAMPLE
    unit = big / VIEW
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    points = [(x * unit, y * unit) for x, y in MARK_PEAK]
    width = REGULAR["stroke"] * unit
    draw.line(points, fill=_hex(LIME), width=round(width), joint="curve")
    for x, y in (points[0], points[-1]):
        draw.ellipse((x - width / 2, y - width / 2, x + width / 2, y + width / 2), fill=_hex(LIME))
    cx, cy = MARK_DOT[0] * unit, MARK_DOT[1] * unit
    r = MARK_DOT_RADIUS * unit
    draw.ellipse((cx - r, cy - r, cx + r, cy + r), fill=_hex(LIME))
    return img.resize((px, px), Image.LANCZOS)


def svg():
    offset, scale = _mark_transform(REGULAR)
    peak = " ".join(f"{'M' if i == 0 else 'L'}{x:g} {y:g}" for i, (x, y) in enumerate(MARK_PEAK))
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW} {VIEW}" role="img" aria-label="Pulse">
  <!-- Pulse app icon (Midnight): lime tile, dark peak mark.
       Generated by tools/branding/make_app_icons.py; edit the script, not this file. -->
  <rect width="{VIEW}" height="{VIEW}" rx="{TILE_RADIUS}" fill="{LIME}"/>
  <g transform="translate({offset:g} {offset:g}) scale({scale:g})" fill="none" stroke="{INK}"
     stroke-width="{REGULAR['stroke']:g}" stroke-linecap="round" stroke-linejoin="round">
    <path d="{peak}"/>
    <circle cx="{MARK_DOT[0]:g}" cy="{MARK_DOT[1]:g}" r="{MARK_DOT_RADIUS:g}" fill="{INK}" stroke="none"/>
  </g>
</svg>
"""


def write_ico(path, renders):
    largest = renders[max(ICO_SIZES)]
    largest.save(
        path,
        format="ICO",
        sizes=[(s, s) for s in ICO_SIZES],
        append_images=[renders[s] for s in ICO_SIZES if s != max(ICO_SIZES)],
    )


def main():
    renders = {px: render(px) for px in PNG_SIZES}
    (BRANDING / "app_icon.svg").write_text(svg(), encoding="utf-8")
    for px in PNG_SIZES:
        renders[px].save(BRANDING / f"app_icon_{px}.png", optimize=True)
    renders[512].save(BRANDING / "app_icon.png", optimize=True)
    renders[256].save(BRANDING / "taskbar_icon.png", optimize=True)
    render_mark(128).save(BRANDING / "mark.png", optimize=True)
    write_ico(BRANDING / "app_icon.ico", renders)
    write_ico(RUNNER_ICO, renders)
    print(f"Wrote icon set to {BRANDING} and {RUNNER_ICO}")


if __name__ == "__main__":
    main()
